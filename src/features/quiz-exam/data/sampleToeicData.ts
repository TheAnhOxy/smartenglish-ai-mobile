export const createSampleExamResult = (answers: Record<string, string>, timeSpentSeconds: number): ExamAttemptResult => {
  let correctCount = 0;
  let wrongCount = 0;
  let unansweredCount = 0;
  let listeningCorrect = 0;
  let readingCorrect = 0;

  const resultQuestions = SAMPLE_TOEIC_QUESTIONS.map((q) => {
    const userAns = answers[q.id];
    const isCorrect = userAns ? userAns === q.correctAnswer : false;
    if (!userAns) unansweredCount++;
    else if (isCorrect) {
      correctCount++;
      if (['PART_1', 'PART_2', 'PART_3', 'PART_4'].includes(q.part)) listeningCorrect++;
      else readingCorrect++;
    } else {
      wrongCount++;
    }

    return {
      ...q,
      selectedAnswer: userAns as any,
      isCorrect,
    };
  });

  const listeningScore = Math.min(495, Math.max(5, Math.round((listeningCorrect / 10) * 495)));
  const readingScore = Math.min(495, Math.max(5, Math.round((readingCorrect / 9) * 495)));
  const displayScore = listeningScore + readingScore;

  return {
    attemptId: 9999,
    examId: 9999,
    title: 'Đề thi thử TOEIC ETS 2024 (Đầy đủ 7 Parts)',
    category: 'TOEIC_FULL',
    cefrLevel: 'B2',
    durationMinutes: 120,
    totalQuestions: SAMPLE_TOEIC_QUESTIONS.length,
    passingScore: 550,
    scorePercentage: Math.round((correctCount / SAMPLE_TOEIC_QUESTIONS.length) * 100),
    displayScore,
    maximumScore: 990,
    scoringType: 'TOEIC_ESTIMATED',
    passed: displayScore >= 550,
    correctAnswers: correctCount,
    wrongAnswers: wrongCount,
    unanswered: unansweredCount,
    xpEarned: Math.min(150, correctCount * 10),
    timeSpentSeconds,
    startedAt: new Date(Date.now() - timeSpentSeconds * 1000).toISOString(),
    submittedAt: new Date().toISOString(),
    questions: resultQuestions,
  };
};
